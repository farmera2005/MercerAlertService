/**
 * Writes .env.example from the env schema and the settings registry, so every operator setting is
 * listed with its default.   pnpm env:example
 *
 * The file is optional documentation for infrastructure-as-code installs: everything in it can be
 * set in the web UI instead. `env-example.test.ts` fails when a registry key is missing.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  envSchema,
  SETTING_SECTIONS,
  SETTINGS,
  type SettingSection,
} from '../packages/core/src/index';

const OUT = fileURLToPath(new URL('../.env.example', import.meta.url));

/** Variables that are read from the environment only (bootstrap, logging, dev switches). */
const ENV_ONLY_NOTES: Record<string, string> = {
  DATABASE_URL:
    'Compose sets DATABASE_URL_FILE=/bootstrap/database_url, written by the init container',
  MAS_MASTER_KEY:
    'Compose sets MAS_MASTER_KEY_FILE=/bootstrap/master_key, written by the init container',
  MAS_DATA_DIR: 'local development only',
  MAS_SETUP_COMPLETE: 'skip the wizard when everything is set here',
};
/** Set by the images themselves; overriding them only causes trouble. */
const NOT_LISTED = new Set(['NODE_ENV', 'APP_VERSION']);

const shape = envSchema.shape as Record<
  string,
  { safeParse(v: unknown): { success: boolean; data?: unknown } }
>;

function defaultOf(key: string): string {
  const r = shape[key]?.safeParse(undefined);
  if (!r?.success || r.data === undefined || r.data === null) return '';
  return Array.isArray(r.data) ? r.data.join(',') : String(r.data);
}

const rule = (title: string) => `# ${'-'.repeat(64)} ${title}`;

const lines: string[] = [
  '# ─────────────────────────────────────────────────────────────────────────────────────────────',
  '# OPTIONAL. MercerAlertService needs NO configuration file: run `docker compose up -d` and finish',
  '# setup in the browser. Everything in the "web UI" blocks can be set in Settings instead.',
  '#',
  '# Use a .env file only for infrastructure-as-code. A variable set here OVERRIDES the web UI and',
  '# shows as "set by environment" (locked) there. Any secret may be given as a file instead, as',
  '# <NAME>_FILE=/run/secrets/<file>. Values shown are the defaults.',
  '#',
  '# Each description is on its own line on purpose: Compose reads "KEY=   # text" as the value',
  '# "# text" when the value is empty, so never put a comment after a setting.',
  '#',
  '# Generated by `pnpm env:example` from packages/core/src/config (do not edit by hand).',
  '# ─────────────────────────────────────────────────────────────────────────────────────────────',
  '',
  rule('Docker Compose (host side)'),
  '# Dashboard port on the VM. Behind a reverse proxy on the same VM, use 127.0.0.1:3000 so only',
  '# the proxy can reach it.',
  '# WEB_PORT=3000',
  '# Postgres port, always bound to 127.0.0.1 (for psql on the VM).',
  '# DB_PORT=5432',
  '# Image tag. The upgrade steps pass it on the command line (from git describe).',
  '# APP_VERSION=dev',
  '# Daily backup time (local time in APP_TIMEZONE) and how many days of dumps to keep.',
  '# BACKUP_TIME=02:30',
  '# BACKUP_KEEP_DAYS=14',
  '# Where dumps are written on the VM, e.g. /mnt/mas-backups (a NAS share).',
  '# BACKUP_HOST_DIR=./backups',
  '# Pin the database password on FIRST start instead of generating one.',
  '# POSTGRES_PASSWORD=',
  '# Extra CA for building behind a TLS-inspecting proxy (a path inside the project).',
  '# BUILD_CA_FILE=./secrets/corp-ca.pem',
  '',
];

const registryKeys = new Set(SETTINGS.map((d) => d.key as string));
const envOnly = Object.keys(shape).filter((k) => !registryKeys.has(k) && !NOT_LISTED.has(k));
lines.push(rule('environment only (not in the web UI)'));
for (const k of envOnly) {
  const note = ENV_ONLY_NOTES[k];
  if (note) lines.push(`# (${note})`);
  lines.push(`# ${k}=${defaultOf(k)}`);
}
lines.push('');

const bySection = new Map<SettingSection, typeof SETTINGS>();
for (const d of SETTINGS) bySection.set(d.section, [...(bySection.get(d.section) ?? []), d]);
for (const [section, defs] of bySection) {
  lines.push(rule(`web UI: ${SETTING_SECTIONS[section].title}`));
  for (const d of defs) {
    const value = d.kind === 'secret' ? '' : defaultOf(d.key);
    lines.push(`# ${d.label}${d.kind === 'secret' ? ' (secret)' : ''}`);
    lines.push(`# ${d.key}=${value}`);
  }
  lines.push('');
}

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${SETTINGS.length} settings, ${envOnly.length} environment-only`);

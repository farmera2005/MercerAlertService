import {
  createCipheriv,
  createDecipheriv,
  createHash,
  hkdfSync,
  randomBytes,
  randomInt,
  scrypt as scryptCb,
  timingSafeEqual,
  type ScryptOptions,
} from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { resolveFileEnv } from './config/file-env';

/**
 * AES-256-GCM envelope for secrets stored in the database (Orion password, later webhook URLs
 * and API keys). Format: "v1:" + base64(iv[12] | tag[16] | ciphertext). The key never touches
 * the database: it comes from MAS_MASTER_KEY(_FILE), generated by the `init` container.
 */
export class SecretBox {
  private readonly key: Buffer;

  constructor(key: Buffer) {
    if (key.length !== 32) throw new Error('master key must be 32 bytes');
    this.key = key;
  }

  static fromBase64(b64: string): SecretBox {
    return new SecretBox(Buffer.from(b64.trim(), 'base64'));
  }

  seal(plaintext: string): string {
    const iv = randomBytes(12);
    const cipher = createCipheriv('aes-256-gcm', this.key, iv);
    const ct = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final()]);
    return 'v1:' + Buffer.concat([iv, cipher.getAuthTag(), ct]).toString('base64');
  }

  /**
   * A stable secret for another purpose (e.g. the Auth.js session key), derived with HKDF so the
   * master key itself is never handed out and no extra secret needs configuring.
   */
  deriveSecret(purpose: string): string {
    return Buffer.from(
      hkdfSync('sha256', this.key, Buffer.alloc(0), `mas:${purpose}`, 32),
    ).toString('base64url');
  }

  open(sealed: string): string {
    if (!sealed.startsWith('v1:')) throw new Error('unknown secret format');
    const raw = Buffer.from(sealed.slice(3), 'base64');
    const decipher = createDecipheriv('aes-256-gcm', this.key, raw.subarray(0, 12));
    decipher.setAuthTag(raw.subarray(12, 28));
    return Buffer.concat([decipher.update(raw.subarray(28)), decipher.final()]).toString('utf8');
  }
}

export function generateMasterKey(): string {
  return randomBytes(32).toString('base64');
}

/**
 * Master key: MAS_MASTER_KEY / MAS_MASTER_KEY_FILE if set (Docker: written by `init`), otherwise
 * `<MAS_DATA_DIR or ~/.mas>/master.key`, created on first use. Creation is race-safe so the web and
 * worker processes of a local dev setup end up with the same key.
 */
export function loadOrCreateMasterKey(env: NodeJS.ProcessEnv = process.env): {
  box: SecretBox;
  source: string;
} {
  const resolved = resolveFileEnv(env, (k) => k === 'MAS_MASTER_KEY');
  if (resolved.MAS_MASTER_KEY)
    return { box: SecretBox.fromBase64(resolved.MAS_MASTER_KEY), source: 'env' };
  const file = join(resolved.MAS_DATA_DIR ?? join(homedir(), '.mas'), 'master.key');
  try {
    return { box: SecretBox.fromBase64(readFileSync(file, 'utf8')), source: file };
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
  }
  mkdirSync(dirname(file), { recursive: true, mode: 0o700 });
  try {
    writeFileSync(file, generateMasterKey() + '\n', { flag: 'wx', mode: 0o600 });
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'EEXIST') throw err;
  }
  return { box: SecretBox.fromBase64(readFileSync(file, 'utf8')), source: file };
}

